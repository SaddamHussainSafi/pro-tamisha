JOB_FN = """
CREATE OR REPLACE FUNCTION scan_job_guard() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'scan jobs cannot be deleted';
  END IF;
  IF NEW.company_id <> OLD.company_id OR NEW.job_no <> OLD.job_no
     OR NEW.channel <> OLD.channel OR NEW.job_type <> OLD.job_type
     OR NEW.warehouse_id <> OLD.warehouse_id OR NEW.requested_by <> OLD.requested_by
     OR NEW.device_id IS DISTINCT FROM OLD.device_id THEN
    RAISE EXCEPTION 'scan job identity is immutable';
  END IF;
  IF OLD.document_id IS NOT NULL AND NEW.document_id IS DISTINCT FROM OLD.document_id THEN
    RAISE EXCEPTION 'scan job source document cannot be replaced';
  END IF;
  IF OLD.status IN ('UPLOADED','FAILED','CANCELLED','EXPIRED') AND NEW.status <> OLD.status THEN
    RAISE EXCEPTION 'scan job % is final', OLD.status;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
"""

DEVICE_FN = """
CREATE OR REPLACE FUNCTION scan_device_guard() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'scan devices cannot be deleted (revoke instead)';
  END IF;
  IF NEW.company_id <> OLD.company_id THEN
    RAISE EXCEPTION 'scan device identity is immutable';
  END IF;
  IF OLD.status = 'REVOKED' AND NEW.status <> 'REVOKED' THEN
    RAISE EXCEPTION 'a revoked scan device cannot be re-activated (pair again)';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
"""

