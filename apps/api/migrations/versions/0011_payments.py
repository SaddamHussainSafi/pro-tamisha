PAYMENT_FN = """
CREATE OR REPLACE FUNCTION payment_guard() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'payments cannot be deleted (reject or reverse instead)';
  END IF;
  IF NEW.company_id <> OLD.company_id OR NEW.payment_no <> OLD.payment_no
     OR NEW.customer_id <> OLD.customer_id OR NEW.method <> OLD.method
     OR NEW.amount <> OLD.amount OR NEW.currency <> OLD.currency
     OR NEW.received_on <> OLD.received_on OR NEW.recorded_by <> OLD.recorded_by
     OR NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION 'recorded payment details are immutable';
  END IF;
  IF OLD.status = 'REJECTED' AND NEW.status <> 'REJECTED' THEN
    RAISE EXCEPTION 'a rejected payment cannot be reopened';
  END IF;
  IF OLD.status IN ('VERIFIED','APPLIED') AND (NEW.status NOT IN ('VERIFIED','APPLIED')
     OR NEW.verification_ref IS DISTINCT FROM OLD.verification_ref
     OR NEW.verified_by IS DISTINCT FROM OLD.verified_by
     OR NEW.verified_at IS DISTINCT FROM OLD.verified_at) THEN
    RAISE EXCEPTION 'verification evidence is immutable';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
"""

ALLOCATION_FN = """
CREATE OR REPLACE FUNCTION payment_allocation_guard() RETURNS trigger AS $$
DECLARE
  p payments%ROWTYPE;
  inv invoices%ROWTYPE;
  psum numeric;
  isum numeric;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'payment allocations are append-only (post a reversal)';
  END IF;
  SELECT * INTO p FROM payments WHERE id = NEW.payment_id;
  SELECT * INTO inv FROM invoices WHERE id = NEW.invoice_id;
  IF p.status NOT IN ('VERIFIED','APPLIED') THEN
    RAISE EXCEPTION 'only verified payments can be allocated';
  END IF;
  IF p.company_id <> NEW.company_id OR inv.company_id <> NEW.company_id
     OR inv.customer_id <> p.customer_id THEN
    RAISE EXCEPTION 'allocation must stay within one company and customer';
  END IF;
  SELECT coalesce(sum(amount), 0) INTO psum FROM payment_allocations
   WHERE payment_id = NEW.payment_id;
  SELECT coalesce(sum(amount), 0) INTO isum FROM payment_allocations
   WHERE invoice_id = NEW.invoice_id;
  IF psum + NEW.amount > p.amount OR psum + NEW.amount < 0 THEN
    RAISE EXCEPTION 'allocations would exceed the verified payment amount';
  END IF;
  IF isum + NEW.amount > inv.total OR isum + NEW.amount < 0 THEN
    RAISE EXCEPTION 'allocations would exceed the invoice total';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
"""


