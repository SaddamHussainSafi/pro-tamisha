LINE_FN = """
CREATE OR REPLACE FUNCTION sales_order_line_guard() RETURNS trigger AS $$
DECLARE st text;
BEGIN
  SELECT status INTO st FROM sales_orders WHERE id = OLD.order_id;
  IF TG_OP = 'DELETE' THEN
    IF st <> 'DRAFT' THEN
      RAISE EXCEPTION 'order lines can only be removed from drafts';
    END IF;
    RETURN OLD;
  END IF;
  IF NEW.order_id <> OLD.order_id OR NEW.line_no <> OLD.line_no THEN
    RAISE EXCEPTION 'order line identity is immutable';
  END IF;
  IF st <> 'DRAFT' AND (NEW.product_id <> OLD.product_id OR NEW.unit_code <> OLD.unit_code
     OR NEW.ordered_qty <> OLD.ordered_qty OR NEW.source_line_text <> OLD.source_line_text) THEN
    RAISE EXCEPTION 'confirmed order lines are immutable (use an amendment)';
  END IF;
  IF OLD.rate IS NOT NULL AND (NEW.rate IS DISTINCT FROM OLD.rate
     OR NEW.price_snapshot IS DISTINCT FROM OLD.price_snapshot) THEN
    RAISE EXCEPTION 'order price is fixed once confirmed';
  END IF;
  IF NEW.cancelled_qty < OLD.cancelled_qty OR NEW.dispatched_qty < OLD.dispatched_qty THEN
    RAISE EXCEPTION 'cancelled/dispatched quantities never decrease';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
"""

